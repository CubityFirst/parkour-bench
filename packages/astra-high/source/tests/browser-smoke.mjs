import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launchPersistentContext(`${process.cwd()}/.browser-profile`, { channel: 'chromium', headless: true, viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, args: ['--enable-webgl', '--ignore-gpu-blocklist', ...(process.platform === 'darwin' ? ['--use-angle=metal'] : [])], env: { ...process.env, TMPDIR: `${process.cwd()}/.tmp` } });
try {
const page = browser.pages()[0];
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
await page.goto(process.env.GAME_URL || 'http://localhost:5173', { waitUntil: 'networkidle' });
await page.waitForTimeout(1800);
await page.screenshot({ path: 'artifacts/title-screen.png' });
assert.ok(await page.locator('#start').isVisible());
console.log('title rendered');
await page.locator('#controls').click();
assert.ok(await page.locator('.controls-grid').isVisible());
await page.locator('#close-modal').click();
await page.locator('#settings').click();
await page.locator('#motion-toggle').click();
assert.equal(await page.locator('#motion-toggle').textContent(), 'Reduced');
await page.locator('#motion-toggle').click();
await page.locator('#close-modal').click();
await page.bringToFront();
await page.locator('#start').click();
await page.waitForTimeout(300);
console.log('start', await page.evaluate(() => ({state: window.__upshift.state, locked: !!document.pointerLockElement, position: window.__upshift.player.position.toArray(), calls: window.__upshift.renderer.info.render.calls, triangles: window.__upshift.renderer.info.render.triangles})));
await page.keyboard.down('Shift'); await page.keyboard.down('w');
await page.waitForTimeout(900);
await page.keyboard.up('w'); await page.keyboard.up('Shift');
await page.screenshot({path: 'artifacts/gameplay.png'});
assert.ok(await page.evaluate(() => window.__upshift.player.position.z < -7));
await page.keyboard.press('Escape'); await page.waitForTimeout(100);
assert.ok(await page.locator('#pause').isVisible());
const pausedTime = await page.evaluate(() => window.__upshift.elapsed);
await page.waitForTimeout(150);
assert.equal(await page.evaluate(() => window.__upshift.elapsed), pausedTime);
await page.bringToFront();
await page.locator('#checkpoint-restart').click();
await page.waitForTimeout(150);
assert.ok(await page.evaluate(() => Math.abs(window.__upshift.player.position.z + 5) < 0.1));
await page.keyboard.press('Escape');
console.log('errors', errors);
assert.deepEqual(errors, []);
} finally { await browser.close(); }
